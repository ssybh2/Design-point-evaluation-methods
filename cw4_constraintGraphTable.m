function T = cw4_constraintGraphTable(C)
% Converts the constraint graph curves into a table for traceability.
T = table(C.WS, C.TW_takeoff, C.TW_cruise, C.TW_cruise_alt, C.TW_oei, C.TW_lower, ...
    repmat(C.WS_landing_weight, numel(C.WS), 1), ...
    repmat(C.WS_landing_takeoff, numel(C.WS), 1), ...
    repmat(C.betaLanding, numel(C.WS), 1), ...
    'VariableNames', {'WS_Nm2','TW_takeoff','TW_cruise_seaLevel','TW_cruise_altitude','TW_OEI','TW_activeEnvelope','WS_landing_weight_limit','WS_takeoff_axis_landing_limit','betaLanding'});
end
